def build_index():
    """Builds the vector index from CSV files and initializes the retrieval system."""
    try:
        diseases_df = pd.read_csv("diseases.csv")
        symptoms_df = pd.read_csv("symptoms.csv")
        print(f"✅ Loaded diseases.csv ({diseases_df.shape[0]} rows, {diseases_df.shape[1]} columns)")
        print(f"✅ Loaded symptoms.csv ({symptoms_df.shape[0]} rows, {symptoms_df.shape[1]} columns)")
    except Exception as e:
        print(f"❌ CSV Loading Error: {e}")
        return None

    try:
        disease_documents = [
            Document(page_content=f"Disease: {row['disease_name']}. Description: {row.get('description', 'No description available.')}")
            for _, row in diseases_df.iterrows()
        ]
        symptom_documents = [
            Document(page_content=f"Disease: {row['disease_name']}. Symptom: {row['symptom']}. Details: {row.get('description', 'No details available.')}")
            for _, row in symptoms_df.iterrows()
        ]
        all_documents = disease_documents + symptom_documents

        text_splitter = RecursiveCharacterTextSplitter(chunk_size=1024, chunk_overlap=100)
        documents = text_splitter.split_documents(all_documents)
    except Exception as e:
        print(f"❌ Document Processing Error: {e}")
        return None

    try:
        embeddings = OpenAIEmbeddings(openai_api_key=openai_api_key)
        vector_store = Chroma(persist_directory="./chroma_db", embedding_function=embeddings)
        vector_store.add_documents(documents)
        print("✅ Documents embedded and stored successfully in ChromaDB")
    except Exception as e:
        print(f"❌ Vector Store Error: {e}")
        return None

    try:
        llm = ChatOpenAI(model="o3-mini", openai_api_key=openai_api_key)
        retriever = SelfQueryRetriever.from_llm(
            llm, vector_store, "Medical information database", [], search_kwargs={"k": 5}
        )

        prompt = PromptTemplate.from_template("""Given the following context, answer the question:
        {context}

        Question: {question}""")

        # Define the new RunnableSequence for the retrieval chain
        qa_chain = (
            {"context": retriever, "question": RunnablePassthrough()}  # Pass retriever output as context
            | prompt  # Apply prompt template
            | llm  # Pass the structured prompt into LLM
        )

        print("✅ Index built successfully. Retrieval system is active.")
        return qa_chain
    except Exception as e:
        print(f"❌ Query Engine Initialization Error: {e}")
        return None

