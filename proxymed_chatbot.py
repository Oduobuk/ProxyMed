def extract_diseases_and_symptoms(json_file_path, diseases_csv_path, symptoms_csv_path):
    """
    Extracts disease and symptom information from a JSON file and saves them
    into separate CSV files.

    Args:
        json_file_path (str): Path to the input JSON file.
        diseases_csv_path (str): Path to the output CSV file for diseases.
        symptoms_csv_path (str): Path to the output CSV file for symptoms.
    """

    try:
        with open(json_file_path, 'r') as json_file:
            data = json.load(json_file)
    except FileNotFoundError:
        print(f"Error: JSON file not found at {json_file_path}")
        return
    except json.JSONDecodeError:
        print(f"Error: Invalid JSON format in {json_file_path}")
        return

    symptoms_data = data.get("symptoms")
    if not symptoms_data:
        print("Error: 'symptoms' key not found in JSON data.")
        return

    # --- Prepare and Write Diseases CSV ---
    disease_header = ["_id", "disease_name"]
    try:
        with open(diseases_csv_path, 'w', newline='', encoding='utf-8') as diseases_csv_file:
            disease_writer = csv.writer(diseases_csv_file)
            disease_writer.writerow(disease_header)

            for symptom_id, symptom_info in symptoms_data.items():
                # For conditions nested inside symptoms info
                if "conditions" in symptom_info and isinstance(symptom_info["conditions"], list):
                    for condition in symptom_info["conditions"]:
                        disease_name = condition.get("name", "")
                        disease_writer.writerow([symptom_info["_id"], disease_name])
                else: # standard format for the conditions
                    condition_data = symptom_info.get("condition")
                    if condition_data:
                         disease_name = condition_data.get("name", "")
                         disease_writer.writerow([symptom_info["_id"], disease_name])

    except Exception as e:
        print(f"An error occurred during diseases CSV writing: {e}")
        return

    # --- Prepare and Write Symptoms CSV ---
    symptom_header = ["_id", "disease_name", "symptom", "description"]
    try:
        with open(symptoms_csv_path, 'w', newline='', encoding='utf-8') as symptoms_csv_file:
            symptom_writer = csv.writer(symptoms_csv_file)
            symptom_writer.writerow(symptom_header)

            for symptom_id, symptom_info in symptoms_data.items():
                #standard format for the conditions
                condition_data = symptom_info.get("condition")
                if condition_data:
                    disease_name = condition_data.get("name", "")

                    # Handle the case where 'symptoms' is a list of dictionaries (Pharyngitis)
                    if "symptoms" in condition_data and isinstance(condition_data["symptoms"], list):
                        for symptom_entry in condition_data["symptoms"]:
                            symptom = symptom_entry.get("symptom", "")
                            description = symptom_entry.get("description", "")
                            symptom_writer.writerow([symptom_info["_id"], disease_name, symptom, description])

                    # Handle the case where 'Primary_Symptoms' is a list of dictionaries (Pharyngitis (Non-Strep))
                    elif "Primary_Symptoms" in condition_data and isinstance(condition_data["Primary_Symptoms"], list):
                        for symptom_entry in condition_data["Primary_Symptoms"]:
                            symptom = symptom_entry.get("Symptom", "")
                            description = symptom_entry.get("Description", "")
                            symptom_writer.writerow([symptom_info["_id"], disease_name, symptom, description])
                #For conditions nested inside symptoms info
                elif "conditions" in symptom_info and isinstance(symptom_info["conditions"], list):
                    for condition in symptom_info["conditions"]:
                        disease_name = condition.get("name", "")
                        if "Primary_Symptoms" in condition and isinstance(condition["Primary_Symptoms"], list):
                            for symptom_entry in condition["Primary_Symptoms"]:
                                symptom = symptom_entry.get("Symptom", "")
                                description = symptom_entry.get("Description", "")
                                symptom_writer.writerow([symptom_info["_id"], disease_name, symptom, description])
                # Handle single symptom/description pairs
                else:
                    symptoms_list = condition_data.get("symptoms", [])
                    if isinstance(symptoms_list, list):  # if it is a list we need to parse out the description/symptom for each
                        for symptom_obj in symptoms_list:
                            symptom = symptom_obj.get("symptom", "")
                            description = symptom_obj.get("description", "")
                            symptom_writer.writerow([symptom_info["_id"], disease_name, symptom, description])

    except Exception as e:
        print(f"An error occurred during symptoms CSV writing: {e}")
        return

    print(f"Successfully extracted diseases to {diseases_csv_path}")
    print(f"Successfully extracted symptoms to {symptoms_csv_path}")

